const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
test('chat reads canonical board, persists owner messages and rejects unsafe requests', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'noble-chat-test-'));
  const previous = process.env.NOBLE_AGENT_BOARD_DIR;
  process.env.NOBLE_AGENT_BOARD_DIR = dir;
  const { createChatServer } = require('./server.cjs');
  const server = createChatServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await fs.rm(dir, { recursive: true, force: true }); if (previous === undefined) delete process.env.NOBLE_AGENT_BOARD_DIR; else process.env.NOBLE_AGENT_BOARD_DIR = previous; });
  assert.equal((await fetch(url)).status, 200);
  assert.match((await fetch(url)).headers.get('content-security-policy'), /frame-ancestors 'none'/);
  assert.equal((await (await fetch(url + '/api/board')).json()).events.length, 0);
  const post = (body, origin = url, type = 'application/json') => fetch(url + '/api/messages', { method: 'POST', headers: { 'Content-Type': type, Origin: origin }, body: JSON.stringify(body) });
  assert.equal((await post({ message: 'Test 🟢 <script>text only</script>', agent: 'noble-main' })).status, 201);
  const state = await (await fetch(url + '/api/board')).json();
  assert.equal(state.events.length, 1);
  assert.equal(state.events[0].agent, 'owner');
  assert.equal(state.events[0].message, 'Test 🟢 <script>text only</script>');
  assert.equal((await post({ message: 'bad' }, 'https://unrelated.example')).status, 403);
  assert.equal((await post({ message: 'bad' }, url, 'text/plain')).status, 415);
  assert.equal((await post({ message: ' '.repeat(20) })).status, 400);
  assert.equal((await post({ message: 'x'.repeat(3001) })).status, 400);
  assert.equal((await post({ message: 'x'.repeat(17000) })).status, 413);
  assert.equal((await fetch(url + '/scripts/agent-board.cjs')).status, 404);
  assert.equal((await fetch(url + '/api/board', { method: 'DELETE' })).status, 404);
  assert.equal((await (await fetch(url + '/api/board')).json()).events.length, 1);
});
